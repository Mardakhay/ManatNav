const COPY: Record<Language, Record<keyof typeof ENGLISH, string>> = {
  en: ENGLISH,
  az: AZERBAIJANI,
};

export type CopyKey = keyof typeof ENGLISH;

export function translate(
  language: Language,
  key: CopyKey,
  values: Record<string, string | number> = {}
): string {
  return COPY[language][key].replace(/\{(\w+)\}/g, (_, name: string) =>
    String(values[name] ?? `{${name}}`)
  );
}
